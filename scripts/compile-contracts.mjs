import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { keccak256 } from "ethers";

const root = fileURLToPath(new URL("../", import.meta.url));
const compilerVersion = "0.8.24";
export async function compileContracts(extraSources = {}) {
  const candidates = [process.env.SOLC_BIN, "solc", join(homedir(), "Library/Application Support/svm/0.8.24/solc-0.8.24")].filter(Boolean);
  const selected = process.env.SOLC_BIN || (existsSync(candidates.at(-1)) ? candidates.at(-1) : "solc");
  const version = await new Promise((resolve, reject) => {
    const child = spawn(selected, ["--version"]); let text = "";
    child.stdout.on("data", value => { text += value; });
    child.on("error", () => reject(new Error("Install Solidity 0.8.24 and set SOLC_BIN to its executable.")));
    child.on("close", code => code === 0 ? resolve(text) : reject(new Error("Solidity compiler could not start.")));
  });
  if (!version.includes(`${compilerVersion}+`)) throw new Error("Use Solidity 0.8.24 for reproducible contract builds.");
  const sources = { "contracts/ForkNightReleases.sol": { content: await readFile(join(root, "contracts/ForkNightReleases.sol"), "utf8") }, ...extraSources };
  const input = { language: "Solidity", sources, settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "metadata"] } } } };
  const output = await new Promise((resolve, reject) => {
    const child = spawn(selected, ["--standard-json"]); let text = "", error = "";
    child.stdout.on("data", value => { text += value; }); child.stderr.on("data", value => { error += value; });
    child.on("error", reject); child.on("close", code => code === 0 ? resolve(text) : reject(new Error(error)));
    child.stdin.end(JSON.stringify(input));
  });
  const compiled = JSON.parse(output);
  const failures = compiled.errors?.filter(error => error.severity === "error") ?? [];
  if (failures.length) throw new Error(failures.map(error => error.formattedMessage).join("\n"));
  const contract = compiled.contracts["contracts/ForkNightReleases.sol"].ForkNightReleases;
  const artifact = { compiler: compilerVersion, abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}`, deployedBytecode: `0x${contract.evm.deployedBytecode.object}`, metadata: contract.metadata };
  await mkdir(join(root, ".local/contracts"), { recursive: true });
  await writeFile(join(root, ".local/contracts/standard-input.json"), JSON.stringify(input, null, 2) + "\n");
  await writeFile(join(root, ".local/contracts/ForkNightReleases.json"), JSON.stringify(artifact, null, 2) + "\n");
  await mkdir(join(root, "src/lib/onchain"), { recursive: true });
  await writeFile(join(root, "src/lib/onchain/abi.ts"), "// Generated by npm run contracts:compile from ForkNightReleases.sol.\nexport const releaseAbi = " + JSON.stringify(contract.abi, null, 2) + " as const;\nexport const releaseRuntimeHash = " + JSON.stringify(keccak256(artifact.deployedBytecode)) + ";\n");
  return { ...artifact, contracts: compiled.contracts };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const artifact = await compileContracts();
  console.log(`Compiled ForkNightReleases with solc ${artifact.compiler}; ${ (artifact.deployedBytecode.length - 2) / 2 } deployed bytes.`);
}
